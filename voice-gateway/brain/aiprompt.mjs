// Ключ тексту першої фрази за видом сесії
function firstKey({ kind, variant, category, v2 }) {
  if (!v2) return kind === 'after_hours' ? (category === 'openRequest' ? 'afterHoursRequest' : 'afterHours') : 'busyLegacy'
  switch (kind) {
    case 'first': return { request: 'firstRequest', general: 'firstGeneral', nodata: 'firstNodata' }[variant] || 'firstNodata'
    case 'after_hours': return category === 'openRequest' ? 'afterHoursRequest' : 'afterHours'
    case 'discussion_failed': return 'dsFailed'
    case 'discussion_unavailable': return 'dsUnavailable'
    case 'discussion_after_hours': return 'dsAfterHours'
    default: return 'busyLegacy'
  }
}
