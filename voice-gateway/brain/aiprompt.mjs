// Черга C: передаємо моделі тільки булеві дозволи, без полів угоди, адрес чи ключа чергового.
export function buildInstructions(options = {}) {
  const { urgentOnly = false, needsTerms = false, resendAllowed = false, exceptionsOnly = false } = options
  let text = buildBaseInstructions(options)
  if (urgentOnly) {
    text = text.replace(/З'єднати з людиною вночі не можна\./g, 'Уночі доступний лише черговий для небезпечної ситуації.')
      .replace(/Співробітники не на зв'язку, з'єднати з людиною не можна\./g, 'Уночі доступний лише черговий для небезпечної ситуації.')
      .replace(/^3\..*$/m, `3. Лише небезпечна ситуація — transfer_to_manager з topic safety. Спершу запиши суть через save_question_for_manager з urgent true, topic safety, callback true, потім скажи: «${URGENT_CONNECTING}» і виклич transfer_to_manager. Звичайна настійлива просьба, претензія чи гарантія не дають нічного переводу.`)
      .replace(/^Небезпека.*$/m, 'Небезпека (акумулятор гріється, дим, займання, травма): технічних порад не давай; спробуй з’єднати з черговим за правилом вище. При загрозі пожежі чи травмі — телефонувати сто дванадцять. Якщо черговий не відповів, питання лишається терміновим і передзвін збережено.')
    if (!options.transferAllowed) text = text.replace(/^3\..*$/m, '3. Черговий зараз недоступний або спробу вже використано. Повторно не з’єднуй; запиши термінове питання і збережи передзвін.')
  }
  if (exceptionsOnly) text += '\nДля transfer_to_manager обов’язково передай topic complaint, warranty або safety; topic other не дозволений.'
  if (needsTerms) {
    text = text.replace(/Режим обговорення: на сторінку заявки клієнта не відсилай[^\n]*/, 'Режим обговорення: спершу правило користувацької угоди, потім запиши питання для менеджера.')
    text += `\nУгоду не прийнято. Перш ніж обговорювати відкриту заявку, скажи: «${TERMS_REQUIRED}» Не стверджуй, що угоду вже прийнято. Небезпечна ситуація має пріоритет.`
  }
  text += resendAllowed
    ? `\nЯкщо клієнт загубив посилання і просить надіслати знову — resend_request_link. Після ok скажи: «${LINK_ACCEPTED}» Доставку не обіцяй; при помилці — «${LINK_MANAGER}», запиши питання лише за згодою.`
    : `\nПовторно надіслати посилання сам ти не можеш. Якщо клієнт його загубив, скажи: «${LINK_MANAGER}», запиши питання лише за згодою.`
  text += '\nВиняток до заборони обіцяти строки: збережений передзвін — протягом восьми робочих годин; це робочі години за оголошеним графіком.'
  if (options.callbackStored === false) text += '\nПередзвін зараз НЕ збережено. Не обіцяй його, доки save_question_for_manager не поверне callback true. Якщо не вдалося — чесно скажи про помилку.'
  return text
}

