const STAGE_UK = {
  received: 'отримано', diagnosed: 'діагностовано', waiting_parts: 'чекаємо запчастини',
  repaired: 'відремонтовано', packed: 'запаковано', shipped: 'відправлено',
}
const STATUS_UK = {
  new: 'нова', diagnostics: 'діагностика', offered: 'запропоновано варіанти ремонту', approved: 'погоджено',
  in_work: 'в роботі', done: 'виконано', cancelled: 'скасовано',
}
const numberOf = (sr) => String(sr?.onec?.number || '').replace(/^0+/, '') || null

// Відповідь інструмента get_request_status. lookup — {requests, profile, orders} | null; lookupState — 'ok' | 'none' |
// 'error' | 'pending' | 'off'. Лише дозволене політикою: без імені, моделі, скарги, сум, телефону.
export function requestStatusFor(lookup, { lookupState = 'ok', detail = 'minimal', nowMs = Date.now(), v2 = false } = {}) {
  if (lookupState === 'off') return { ok: true, found: false, note: 'Перевірка заявок для цього дзвінка недоступна. Запропонуй записати питання для менеджера.' }
  if (!lookup) return { ok: false, error: 'unavailable', note: 'Не вдалося перевірити заявку зараз. Запропонуй записати питання для менеджера.' }
  const { main, mainOpen, openCount } = pickRequests(lookup.requests || [], nowMs)
  const category = clientCategory(lookup, nowMs)
  if (!main) {
    return { ok: true, found: false, knownClient: category === 'knownClient', note: 'Заявок на ремонт за цим номером немає. Можна записати питання для менеджера.' }
  }
  const out = { ok: true, found: true, open: !!mainOpen, openCount, requestNumber: mainOpen ? numberOf(main) : null }
  if (detail === 'stage' && mainOpen) {
    out.stage = STAGE_UK[main.stage] || STATUS_UK[main.status] || null
    out.stageNote = 'Етап — за нашими даними, вони оновлюються раз на добу.'
  }
  out.note = mainOpen
    ? v2
      ? 'Щодо заявки — сторінка заявки за посиланням із SMS або в месенджері, відповідаємо протягом одного робочого дня. Інше питання — запиши для менеджера.'
      : 'Щодо заявки — кабінет за посиланням із SMS або в месенджері, відповідаємо протягом одного робочого дня. Інше питання — запиши для менеджера.'
    : 'Відкритих заявок немає (останню закрито). Якщо питання щодо неї — запиши для менеджера.'
  return out
}

// Підсумок для документа дзвінка і передзвону: «Суть: / Домовилися: / Далі:» — як резюме конвеєра дзвінків.
export function summaryText({ note = null, transferred = false, callbackStored = false } = {}) {
  const gist = note?.question ? note.question : 'Питання не записано.'
  const agreed = transferred
    ? "З'єднано з менеджером."
    : callbackStored && note?.callback !== false
      ? 'Менеджер передзвонить.'
      : note?.callback === false ? 'Клієнт сказав, що передзвонювати не треба.' : 'Нічого.'
  const next = transferred ? 'немає' : callbackStored && note?.callback !== false ? `Передзвонити клієнту${note?.urgent ? ' (термінове)' : ''}.` : 'немає'
  return `Суть: ${gist}\nДомовилися: ${agreed}\nДалі: ${next}`
}
