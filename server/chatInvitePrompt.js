// Служебная реплика «человек открыл приглашение». Беседа-приглашение начинается с реплики ИИ (приветствие с
// вопросами), а Anthropic требует первым user — вместо отбрасывания приветствия (как в обычном чате) ставим её.
export const inviteOpenedTurn = (topic) => `[Службове повідомлення: людина перейшла за запрошенням до чату на тему «${topic}».]`

// Запрос на приветствие (единственная user-реплика при генерации первого сообщения).
export const openingRequest = (topic) =>
  `[Службове повідомлення: людина зараз відкриє запрошення до чату на тему «${topic}». Напиши перше повідомлення: привітайся, коротко назви тему і постав перші уточнювальні питання, без яких не вийде допомогти. Цін не називай. Нічого не вигадуй поза базою знань і нотаткою.]`

// История для ИИ (уже в формате Anthropic, после склейки): если начинается с ассистента — добавить служебную реплику.
export const withInviteLead = (chatMessages, inv) =>
  chatMessages.length && chatMessages[0].role !== 'user'
    ? [{ role: 'user', content: inviteOpenedTurn(inv.topic) }, ...chatMessages]
    : chatMessages
