// Тексты бесед-приглашений (server/chatInvites.js): SMS, приветствие, блок системного промпта и служебная
// реплика для истории. Чистые функции без зависимостей — их используют и чаты сайта (server/index.js), и
// ответ бота по упоминанию менеджера (messengerCore.aiReply), и сам модуль приглашений.

export const SMS_MAX = 134 // 2 сегмента UCS-2 (кириллица): 2 × 67 символов

export const inviteUrl = (siteUrl, sessionId) => `${String(siteUrl || '').replace(/\/$/, '')}/c/${sessionId}`

// Сколько SMS-сегментов займёт текст (кириллица → UCS-2: 70 символов одной SMS, 67 — в составной).
export const smsSegments = (text) => {
  const n = [...String(text || '')].length
  return n <= 70 ? 1 : Math.ceil(n / 67)
}

// Текст SMS-приглашения (укр.). Тема в SMS укорачивается по границе слова, чтобы всё влезло в 2 сегмента
// (полная тема — в шапке чата).
export const inviteSmsText = (topic, url) => {
  const head = 'RunFerry: продовжимо розмову про «'
  const tail = `» у чаті: ${url}`
  const room = Math.max(SMS_MAX - head.length - tail.length, 12)
  let t = String(topic || '')
  if (t.length > room) {
    const cut = t.slice(0, room - 1)
    const space = cut.lastIndexOf(' ')
    t = `${(space >= room / 2 ? cut.slice(0, space) : cut).replace(/[\s,.;:–-]+$/, '')}…`
  }
  return head + t + tail
}

// Запасное приветствие, если ИИ недоступен или не ответил вовремя.
